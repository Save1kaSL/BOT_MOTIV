def get_step_instruction(offer_id: str, step_index: int) -> str:
    texts = STEP_INSTRUCTIONS.get(offer_id)
    if texts and step_index < len(texts):
        return texts[step_index]
    if step_index < len(DEFAULT_LINK_STEPS):
        return DEFAULT_LINK_STEPS[step_index]
    return "Следуй инструкции в карточке оффера."
