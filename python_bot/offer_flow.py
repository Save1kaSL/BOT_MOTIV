"""Конфигурация шагов и тексты инструкций по офферам."""

from __future__ import annotations

from dataclasses import dataclass

# Офферы с анкетой (данные → админу)
FORM_OFFER_IDS = frozenset({"alfa_regbiz", "alfa_rko", "vtb", "uralsib"})


@dataclass(frozen=True)
class OfferFlowConfig:
    form_at_step: int | None = None
    link_at_step: int | None = None
    smz_at_step: int | None = None


FLOW: dict[str, OfferFlowConfig] = {
    "alfa_regbiz": OfferFlowConfig(form_at_step=1, link_at_step=1, smz_at_step=0),
    "alfa_rko": OfferFlowConfig(form_at_step=0, link_at_step=0),
    "vtb": OfferFlowConfig(form_at_step=0),
    "uralsib": OfferFlowConfig(form_at_step=0),
    "loko": OfferFlowConfig(link_at_step=0),
}

DEFAULT_LINK_FLOW = OfferFlowConfig(link_at_step=0)


def get_flow(offer_id: str) -> OfferFlowConfig:
    return FLOW.get(offer_id, DEFAULT_LINK_FLOW)


def needs_form_at_step(offer_id: str, step: int) -> bool:
    return offer_id in FORM_OFFER_IDS and get_flow(offer_id).form_at_step == step


def shows_link_at_step(offer_id: str, step: int) -> bool:
    cfg = get_flow(offer_id)
    return cfg.link_at_step is not None and cfg.link_at_step == step


def is_smz_step(offer_id: str, step: int) -> bool:
    cfg = get_flow(offer_id)
    return cfg.smz_at_step is not None and cfg.smz_at_step == step


